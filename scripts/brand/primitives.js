const c = (hex, a = 'FF') => `Color(0x${a}${hex.slice(1)})`;
const alpha = pct => Math.round(pct / 100 * 255).toString(16).toUpperCase().padStart(2, '0');
const lines = [];
const emit = s => lines.push(s);
function pairs(name, d, l) {
  steps.forEach((s, i) => {
    emit(`  static const p${s}Dark = ${c(Array.isArray(d) ? d[i] : d[s])};`);
    emit(`  static const p${s}Light = ${c(Array.isArray(l) ? l[i] : l[s])};`);
    emit('');
  });
}
function alphas(d, l, list) {
  for (const [step, pct] of list) {
    const i = steps.indexOf(String(step));
    const dh = Array.isArray(d) ? d[i] : d[step], lh = Array.isArray(l) ? l[i] : l[step];
    emit(`  static const p${step}Alpha${pct}Dark = ${c(dh, alpha(pct))};`);
    emit(`  static const p${step}Alpha${pct}Light = ${c(lh, alpha(pct))};`);
    emit('');
  }
}

